// ===== البحث =====
const BRAND_WORDS = ['samsung', 'galaxy', 'xiaomi', 'redmi', 'oppo', 'realme', 'vivo', 'honor', 'tecno', 'infinix'];

function norm(s) {
  let t = String(s || '').toLowerCase();
  BRAND_WORDS.forEach((w) => {
    t = t.split(w).join('');
  });
  return t.replace(/[^a-z0-9+]+/g, '');
}

function findBrand(brand) {
  const b = norm('') + String(brand || '').toLowerCase();
  const keys = Object.keys(MODELS);
  for (let i = 0; i < keys.length; i++) {
    if (b.indexOf(keys[i].toLowerCase()) !== -1) return keys[i];
  }
  return '';
}

function findModel(brandKey, modelName) {
  const target = norm(modelName);
  if (!target) return null;
  const tiers = Object.keys(MODELS[brandKey]);
  for (let i = 0; i < tiers.length; i++) {
    const list = MODELS[brandKey][tiers[i]];
    for (let j = 0; j < list.length; j++) {
      if (norm(list[j]) === target) return { name: list[j], tier: tiers[i] };
    }
  }
  return null;
}

// يرجّع نص جاهز يتحط في البرومبت، أو '' لو الماركة مش معروفة
function getPhoneInfo(brand, modelName) {
  const brandKey = findBrand(brand);
  if (!brandKey) return '';

  const paths = BRAND_PATHS[brandKey];
  const found = findModel(brandKey, modelName);
  const lines = [];

  lines.push('واجهة النظام: ' + paths.os + '.');
  lines.push('مسارات الإعدادات: وضع المطور: ' + paths.devMode + ' | التحديث: ' + paths.update +
    ' | البطارية: ' + paths.battery + ' | التخزين: ' + paths.storage +
    ' | الوضع الآمن: ' + paths.safeMode + ' | إعادة ضبط الشبكة: ' + paths.network + '.');

  if (found) {
    lines.push('فئة الموديل: ' + TIER_LABEL[found.tier] + '.');
    lines.push('أعطال شائعة في الفئة (تقديري): ' + TIER_FAULTS[found.tier] + '.');
    const note = MODEL_NOTES[brandKey] && MODEL_NOTES[brandKey][found.name];
    if (note) lines.push('ملاحظات من تقارير المستخدمين عن هذا الموديل: ' + note);
  }

  if (BRAND_NOTES[brandKey]) lines.push('ملاحظة عن الماركة: ' + BRAND_NOTES[brandKey]);

  return lines.join('\n');
}

